export interface TaskGroupFields {
  taskGroup: TaskGroup | null
  subgroup: string | null
  /** The surface a key works inside, for a key that is not a command. */
  surface: string | null
}

export function taskGroupFields(id: string): TaskGroupFields {
  const row = TASK_GROUP_TABLE[id]
  if (row) return { taskGroup: row[0], subgroup: row[1], surface: null }
  return { taskGroup: null, subgroup: null, surface: SURFACE_KEYS[id] ?? null }
}

/** The label a list shows for a command or key: its task group, or its surface for a surface key. */
export function taskGroupLabel(id: string): string {
  const fields = taskGroupFields(id)
  return fields.taskGroup ?? fields.surface ?? ''
}
