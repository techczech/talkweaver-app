import assert from 'node:assert/strict';
import { createVideoPlayback } from '../compiler/assets/runtime/video-playback.js';
let clock = 10000;
const c = createVideoPlayback({ now: () => clock, known: s => s.slide === 0 && s.video === 0 });
const p = { currentTime: 5, duration: 12, playbackRate: 1, paused: true, ended: false, loop: false, pause() { this.paused = true; }, play() { this.paused = false; return Promise.resolve(); } };
const id = { slide: 0, video: 0, slideId: 'video', navSeq: 0 };
assert(c.command(p, { action: 'seek', value: 5, nonce: 'seek' }));
assert(!c.command(p, { action: 'seek', value: -1, nonce: 'negative' }));
assert(c.command(p, { action: 'play', nonce: 'a' }));
assert(!c.command(p, { action: 'pause', nonce: 'a' }));
assert(!c.command(p, { action: 'rate', value: Infinity, nonce: 'bad' }));
assert(c.command(p, { action: 'rate', value: 1.5, nonce: 'rate' }));
let s = c.snapshot(p, id);
assert(c.accept(s)); assert(!c.accept(s));
assert(!c.valid({ ...s, time: NaN })); assert(!c.valid({ ...s, video: 8 }));
assert(!c.valid({ ...s, rate: 5 })); assert(!c.valid({ ...s, paused: 'false' }));
clock += 1000;
assert.equal(c.decision(s, { currentTime: 6.4, duration: 12 }).seek, false);
assert.equal(c.decision(s, { currentTime: 5, duration: 12 }).time, 6.5);
const follower = { ...p, currentTime: 0 };
assert(c.apply(s, follower, true)); assert.equal(follower.currentTime, 6.5); assert(follower.muted); assert(c.echo(follower));
follower.currentTime = 9; assert(!c.echo(follower));
assert(c.command(p, { action: 'pause', nonce: 'pause' }));
s = c.snapshot(p, id); clock += 1000; assert.equal(c.decision(s, follower).time, 5);
p.ended = true; s = c.snapshot(p, id); assert(c.decision(s, follower).paused);
p.ended = false; p.paused = false; p.loop = true; p.currentTime = 11;
s = c.snapshot(p, id); clock += 1000; assert.equal(c.decision(s, follower).time, 0.5);
clock += 5000; assert(!c.valid(s));
// A newly loaded presenter starts a new revision sequence; retired owners cannot return.
clock += 1;
const fresh = createVideoPlayback({ presenterId: 'reloaded', now: () => clock, known: () => true });
const reloaded = fresh.snapshot(p, id);
assert(c.accept(reloaded));
assert(!c.accept({ ...s, at: clock, revision: 99999 }), 'retired presenter cannot reclaim ownership');
assert(!c.valid({ ...reloaded, presenterId: '' }));
const matching = createVideoPlayback({ now: () => clock, known: () => true, playerMatches: (snapshot, player) => player === follower });
assert(!matching.apply(reloaded, p, false), 'a snapshot cannot be applied to a different player');
assert(matching.apply(reloaded, follower, false));
console.log('PASS video playback commands, validation, drift 0.25s, echo suppression, late join, pause/end/loop, presenter reload, retired-owner rejection, player identity');
