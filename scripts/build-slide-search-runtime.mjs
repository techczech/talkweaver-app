// Generates compiler/assets/runtime/slide-search.js from src/shared/slide-handling/query.ts: the ONE search rule
// (parse, match, highlight, snippet) for the exported pages and the presenter view, which are plain scripts that cannot
// import src/shared (ticket 2b; option (b), build-time codegen, precedent scripts/build-shortcut-help.mjs).
// The TypeScript file stays the only source; the output is query.ts with its types and comments removed, wrapped in a
// function scope so nothing leaks into the page, and the same names returned as `SlideSearch`.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = join(root, 'src/shared/slide-handling/query.ts')
export const runtimePath = join(root, 'compiler/assets/runtime/slide-search.js')

export function renderSlideSearchRuntime(source = readFileSync(sourcePath, 'utf8')) {
  const names = [...source.matchAll(/^export (?:async )?(?:function|const) ([A-Za-z0-9_]+)/gm)].map((m) => m[1])
  if (names.length === 0) throw new Error('query.ts exports nothing')
  const js = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: true },
  }).outputText.replace(/^export /gm, '').trim()
  if (/^(import|export) /m.test(js)) throw new Error('query.ts must stay free of imports and non-function exports')
  const body = js.split('\n').map((line) => (line ? `  ${line}` : line)).join('\n')
  return `// Generated by scripts/build-slide-search-runtime.mjs from src/shared/slide-handling/query.ts. Do not edit.\n`
    + `// Inlined (no export) before overview.js in the presenter template and the handout (01-cli-utils.overviewRuntimeSource).\n`
    + `const SlideSearch = (() => {\n${body}\n  return { ${names.join(', ')} };\n})();\n`
}

export function writeSlideSearchRuntime() {
  writeFileSync(runtimePath, renderSlideSearchRuntime(), 'utf8')
  return runtimePath
}

if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file:').href) {
  console.log(`slide search runtime → ${writeSlideSearchRuntime()}`)
}
