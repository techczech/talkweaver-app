import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const entriesPath = join(root, 'src/shared/layout-registry/entries.ts')
export const generatedPath = join(root, 'compiler/scripts/lib/trigger-dictionary.generated.mjs')

async function loadRegistry() {
  const source = readFileSync(entriesPath, 'utf8')
  const js = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 }
  }).outputText
  return import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`)
}

function targetFor(entry) {
  if (entry.resolvesTo) return entry.resolvesTo
  if (entry.kind === 'layout') return { key: 'layout', value: entry.name }
  return { key: entry.name, value: true }
}

// ADR-0023 §2: the compiled layout SLUG an entry produces, so the generated title-regime map is
// keyed the way 07-assembly sees a slide. An entry that resolves to another layout contributes its
// target's slug ({trace-dialogue} → trace, {table-outline} → table, {code} → code); a `{role=X}`
// entry also contributes that role's slug ({role=section-title} → section-title, which is what
// 08-source-adapters stamps on a divider).
function layoutSlugsFor(entry) {
  const slugs = new Set()
  if (entry.resolvesTo?.key === 'layout') slugs.add(String(entry.resolvesTo.value))
  else slugs.add(entry.name)
  const role = String(entry.trigger ?? '').match(/^\{role=([\w-]+)\}$/)
  if (role) slugs.add(role[1])
  return [...slugs]
}

export async function generateTriggerDictionarySource() {
  const { FINITE_VALUE_TOKENS, GLOBAL_OPTION_GROUPS, LAYOUTS, OPEN_PATTERN_TOKENS } = await loadRegistry()
  const dictionary = {}
  const titleRegimes = {}
  const dynamicPatterns = []
  const valueTriggers = {}
  const sectionOnlyTriggerKeys = []
  const openPatternKeys = new Set(OPEN_PATTERN_TOKENS.map((token) => token.key))
  const collectValueTrigger = (token) => {
    const at = String(token ?? '').indexOf('=')
    if (at <= 0) return
    const key = token.slice(0, at)
    if (openPatternKeys.has(key)) return
    const value = token.slice(at + 1)
    valueTriggers[key] ??= []
    if (!valueTriggers[key].includes(value)) valueTriggers[key].push(value)
  }
  const collectValueTriggers = (groups) => {
    for (const group of groups ?? []) {
      const tokens = [
        ...(group.dictionaryTokens ?? []),
        ...(group.values ?? []).map((option) => option.token)
      ]
      for (const token of tokens) collectValueTrigger(token)
    }
  }
  for (const entry of LAYOUTS) {
    const target = targetFor(entry)
    const isTriggerToken = String(entry.trigger ?? '').trim().startsWith('{')
    if (isTriggerToken) {
      for (const word of entry.triggerWords) dictionary[word] = target
      for (const alias of entry.bareAliases ?? []) dictionary[alias.word] = { key: alias.key, value: alias.value }
    }
    for (const pattern of entry.dynamicPatterns ?? []) dynamicPatterns.push(pattern)
    if (entry.sectionOnly) {
      const authored = String(entry.trigger ?? '').replace(/^\{|\}$/g, '')
      const explicitKey = authored.match(/^([\w-]+)(?:=|:)/)?.[1]
      sectionOnlyTriggerKeys.push({
        name: entry.name,
        key: entry.resolvesTo?.key ?? explicitKey ?? target.key
      })
    }
    if (entry.titleRegime) {
      for (const slug of layoutSlugsFor(entry)) {
        const seen = titleRegimes[slug]
        if (seen && seen !== entry.titleRegime) {
          throw new Error(`layout slug "${slug}" is declared with two title regimes: ${seen} and ${entry.titleRegime} (${entry.name})`)
        }
        titleRegimes[slug] = entry.titleRegime
      }
    }
    collectValueTriggers(entry.options)
    // Value-form entry triggers and aliases are registry vocabulary too. Keep this path aligned
    // with buildTriggerVocabulary so the Doctor and generated compiler validator see one set.
    for (const raw of [entry.trigger, ...entry.aliases]) {
      collectValueTrigger(String(raw).replace(/^\{|\}$/g, ''))
    }
  }
  collectValueTriggers(GLOBAL_OPTION_GROUPS)
  for (const token of FINITE_VALUE_TOKENS) collectValueTrigger(token)
  valueTriggers.layout = [...new Set(LAYOUTS.flatMap((entry) => [
    ...(entry.kind === 'layout' ? [entry.name] : []),
    ...(entry.resolvesTo?.key === 'layout' ? [String(entry.resolvesTo.value)] : [])
  ]))]
  return `// Generated by scripts/generate-trigger-dictionary.mjs. Do not edit.\n` +
    `export const TRIGGER_DICTIONARY = ${JSON.stringify(dictionary, null, 2)}\n\n` +
    `export const DYNAMIC_PATTERNS = ${JSON.stringify(dynamicPatterns, null, 2)}\n\n` +
    `export const VALUE_TRIGGER_DICTIONARY = ${JSON.stringify(valueTriggers, null, 2)}\n\n` +
    `export const OPEN_PATTERN_TOKENS = ${JSON.stringify(OPEN_PATTERN_TOKENS, null, 2)}\n\n` +
    `export const SECTION_ONLY_TRIGGER_KEYS = ${JSON.stringify(sectionOnlyTriggerKeys, null, 2)}\n\n` +
    `// ADR-0023 §2: title regime per compiled layout slug. The compiler's single source.\n` +
    `export const TITLE_REGIME_BY_LAYOUT = ${JSON.stringify(Object.fromEntries(Object.entries(titleRegimes).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)), null, 2)}\n`
}

export async function writeTriggerDictionary() {
  writeFileSync(generatedPath, await generateTriggerDictionarySource())
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await writeTriggerDictionary()
}
