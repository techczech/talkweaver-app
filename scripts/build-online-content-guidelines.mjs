// Canonical public copy is Markdown. The generated module is shared by the offline
// Guide and compiler outputs, with no runtime fetch or access to the open talk.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const normaliseLineEndings = text => text.replace(/\r\n?/g, '\n')
const source = normaliseLineEndings(readFileSync(resolve(root, 'resources/online-content-guidelines.md'), 'utf8'))
const title = source.match(/^title: (.+)$/m)?.[1]
if (!title) throw new Error('Public guidelines need a title.')
const markdown = source.replace(/^---\n[\s\S]*?\n---\n/, '').trim()
const escape = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;')
const reportLink = markdown.match(/^\[([^\]]+)\]\((https:\/\/[^\s)]+)\)$/m)
if (!reportLink || reportLink[2] !== 'https://github.com/techczech/talkweaver-app/issues') throw new Error('Public reporting must use the existing developer-support destination.')
const body = markdown.split(/\n\s*\n/).map(block => {
  if (block === reportLink[0]) return `<p><a href="${escape(reportLink[2])}" target="_blank" rel="noopener noreferrer" referrerpolicy="no-referrer" data-online-content-report>${escape(reportLink[1])}</a></p>`
  const heading = block.match(/^#{1,2} (.*)$/)
  return heading ? `<h3>${escape(heading[1])}</h3>` : `<p>${escape(block.replaceAll('\n', ' '))}</p>`
}).join('\n')
const url = reportLink[2]
const html = `<details class="tw-online-content" data-online-content-guidelines><summary>${escape(title)}</summary><div class="tw-online-content-body">${body}</div></details>`
const output = `// Generated by scripts/build-online-content-guidelines.mjs from resources/online-content-guidelines.md.\nexport const ONLINE_CONTENT_REPORT_URL = ${JSON.stringify(url)};\nexport const ONLINE_CONTENT_GUIDELINES_HTML = ${JSON.stringify(html)};\nexport function onlineContentGuidelinesHtml() { return ONLINE_CONTENT_GUIDELINES_HTML; }\n`
for (const name of ['compiler/scripts/lib/online-content-guidelines.mjs', 'worker/online-content-guidelines.ts']) {
  const destination = resolve(root, name)
  if (process.argv.includes('--check')) {
    if (normaliseLineEndings(readFileSync(destination, 'utf8')) !== output) throw new Error('Online content guidelines are stale; run npm run generate:online-content-guidelines.')
  } else writeFileSync(destination, output)
}
