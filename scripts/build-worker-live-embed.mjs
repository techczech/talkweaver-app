// Keep the isolated Worker package self-contained without maintaining a second validator.
import { writeFileSync, readFileSync } from 'node:fs'
import { embedProtocolSource } from '../compiler/assets/runtime/embed-protocol.js'
import { normaliseLiveEmbed, liveEmbedKey } from '../compiler/assets/runtime/live-embed.js'
const target = new URL('../worker/live-embed-runtime.ts', import.meta.url)
const parser = normaliseLiveEmbed.toString().replace('function normaliseLiveEmbed(value)', 'function normaliseLiveEmbed(value: unknown): EmbedMessage | null')
const key = liveEmbedKey.toString().replace('function liveEmbedKey(value)', 'function liveEmbedKey(value: EmbedMessage): string')
const rawSource = '// @ts-nocheck\n// Generated by scripts/build-worker-live-embed.mjs; do not edit.\n'
  + "import type { EmbedMessage } from './protocol.ts'\n" + embedProtocolSource() + '\nexport ' + parser + '\nexport ' + key + '\n'
const source = rawSource.replace(/\r\n/g, '\n')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== source) throw new Error('Worker embed validator is stale; run node scripts/build-worker-live-embed.mjs')
} else writeFileSync(target, source)
