import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const templatePath = join(root, 'compiler/assets/templates/presenter-popup-single-html.html')
export const iconsModulePath = join(root, 'src/shared/presenter-icons.generated.ts')
const lucidePath = join(root, 'compiler/assets/icons/lucide.json')
const startMarker = '/*SHORTCUT_HELP*/'
const endMarker = '/*END_SHORTCUT_HELP*/'

async function sources() {
  const { SHORTCUT_REGISTRY } = await import(new URL('../src/shared/shortcut-registry.ts', import.meta.url))
  const controls = await import(new URL('../src/shared/presenter-controls.ts', import.meta.url))
  const palette = await import(new URL('../src/shared/presenter-palette.ts', import.meta.url))
  return { SHORTCUT_REGISTRY, ...controls, ...palette }
}

// The lucide bodies the presenter chrome uses, from the compiler's vendored set (the editor's icons).
export async function presenterIconBodies() {
  const { presenterIconNames } = await sources()
  const lucide = JSON.parse(readFileSync(lucidePath, 'utf8'))
  return Object.fromEntries(presenterIconNames().map((name) => {
    if (!lucide[name]?.body) throw new Error(`lucide icon ${name} is not in compiler/assets/icons/lucide.json`)
    return [name, lucide[name].body]
  }))
}

export async function renderIconsModule() {
  const bodies = await presenterIconBodies()
  return `// Generated by scripts/build-shortcut-help.mjs from compiler/assets/icons/lucide.json. Do not edit.\nexport const PRESENTER_ICON_BODIES: Record<string, string> = ${JSON.stringify(bodies, null, 2)}\n`
}

// The registered reactions for the presenter chip (ticket 04): id → [icon, short name, bar words],
// from the audience runtime's one list, so the chip never keeps a second vocabulary.
async function reactionNames() {
  const { audienceReactionRegistry } = await import(new URL('../compiler/assets/runtime/audience-reactions.js', import.meta.url))
  return Object.fromEntries(Object.entries(audienceReactionRegistry()).map(([id, entry]) => [id, [entry.icon, entry.short, entry.words]]))
}

export async function buildShortcutHelp() {
  const { SHORTCUT_REGISTRY, PRESENTER_CONTROLS, presenterControlTips, presenterIconSvg, TIMER_BUTTON_NAMES, MODE_CHIP_NAMES, OUTLINE_STATUS_ICONS, presenterPaletteData, PRESENTER_KEY_NEEDS } = await sources()
  const bodies = await presenterIconBodies()
  // Template-owned controls only; the preloads dress their own (they inject after the template runs).
  const templateControls = PRESENTER_CONTROLS.filter((control) => !control.preload || control.preload === 'live')
  const tips = presenterControlTips(SHORTCUT_REGISTRY, templateControls)
  const iconOf = Object.fromEntries(templateControls.filter((control) => control.icon).map((control) => [control.id, [control.icon, control.iconAfter ? 1 : 0, control.iconOnly ? 1 : 0]]))
  const icons = Object.fromEntries(Object.keys(bodies).map((name) => [name, presenterIconSvg(name, bodies[name])]))
  const groups = []
  for (const entry of SHORTCUT_REGISTRY.filter((item) => item.scope === 'presenter')) {
    let group = groups.find(([name]) => name === entry.group)
    if (!group) { group = [entry.group, []]; groups.push(group) }
    // A third field names the preload a row's key needs (the ? sheet shows it only when mounted).
    group[1].push([entry.keys, entry.label, PRESENTER_KEY_NEEDS[entry.id] || null, entry.id])
  }
  const paletteData = presenterPaletteData(SHORTCUT_REGISTRY)
  const commandKeys = SHORTCUT_REGISTRY.filter(item => item.scope === 'presenter').map(({ id, label, codes, keys }) => ({ id, label, codes, keys }))
  for (const entry of paletteData.flatMap(([, entries]) => entries)) {
    if (!entry.shortcut) commandKeys.push({ id: `palette.${entry.id}`, label: entry.name, codes: [], keys: '' })
  }
  return [
    `const PRESENTER_COMMAND_KEYS = ${JSON.stringify(commandKeys)};`,
    `const PRESENTER_CONTROL_COMMANDS = ${JSON.stringify(Object.fromEntries(PRESENTER_CONTROLS.filter(item => item.shortcut).map(item => [item.id, item.shortcut])))};`,
    `const PRESENTER_TIPS = ${JSON.stringify(tips)};`,
    `const PRESENTER_ICON_OF = ${JSON.stringify(iconOf)};`,
    `const TIMER_BUTTON = ${JSON.stringify({ names: TIMER_BUTTON_NAMES })};`,
    `const MODE_CHIP = ${JSON.stringify(MODE_CHIP_NAMES)};`,
    `const OUTLINE_STATUS_ICONS = ${JSON.stringify(OUTLINE_STATUS_ICONS)};`,
    `const PRESENTER_ICONS = ${JSON.stringify(icons)};`,
    `const SHORTCUTS_LIST = ${JSON.stringify(groups)};`,
    `const AUDIENCE_REACTION_NAMES = ${JSON.stringify(await reactionNames())};`,
    `const PRESENTER_PALETTE = ${JSON.stringify(presenterPaletteData(SHORTCUT_REGISTRY))};`
  ].join('\n  ')
}

export async function renderTemplateWithShortcutHelp(template = readFileSync(templatePath, 'utf8')) {
  const start = template.indexOf(startMarker)
  const end = template.indexOf(endMarker)
  if (start < 0 || end < start) throw new Error(`Template must contain ${startMarker} and ${endMarker}`)
  const generated = await buildShortcutHelp()
  return `${template.slice(0, start + startMarker.length)}\n  ${generated}\n  ${template.slice(end)}`
}

export async function writeShortcutHelp() {
  // Icons first: the template block is built from the same bodies.
  writeFileSync(iconsModulePath, await renderIconsModule(), 'utf8')
  writeFileSync(templatePath, await renderTemplateWithShortcutHelp(), 'utf8')
  return templatePath
}

if (import.meta.url === new URL(process.argv[1], 'file:').href) {
  console.log(`shortcut help → ${await writeShortcutHelp()}`)
}
